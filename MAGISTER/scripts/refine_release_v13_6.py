def set_paragraph_text_preserve_markers(p, new_text: str, bold: bool = None, font_size_pt: float = 14.0):
    """
    Замінює видимий текст параграфа, гарантовано зберігаючи всі XML-маркери коментарів
    (w:commentRangeStart, w:commentRangeEnd, w:commentReference) та властивості параграфа (w:pPr).
    Використовується лише для текстових параграфів без m:oMath.
    """
    p_elem = p._p
    if 'oMath' in p_elem.xml:
        raise ValueError("Заборонено викликати set_paragraph_text_preserve_markers на параграфі з m:oMath!")

    # Зберігаємо pPr та всі елементи коментарів
    saved_comment_Starts = []
    saved_comment_Ends = []
    saved_comment_Refs = []

    for child in list(p_elem):
        tag = child.tag.split('}')[-1]
        if tag == 'pPr':
            continue
        elif tag == 'commentRangeStart':
            saved_comment_Starts.append(child)
            p_elem.remove(child)
        elif tag == 'commentRangeEnd':
            saved_comment_Ends.append(child)
            p_elem.remove(child)
        elif tag == 'commentReference':
            saved_comment_Refs.append(child)
            p_elem.remove(child)
        else:
            # Перевіряємо, чи всередині w:r немає commentReference
            refs_in_r = [c for c in child if c.tag.split('}')[-1] == 'commentReference']
            if refs_in_r:
                saved_comment_Refs.extend(refs_in_r)
            p_elem.remove(child)

    # Додаємо commentRangeStart на початок (після pPr)
    for cs in saved_comment_Starts:
        p_elem.append(cs)

    # Створюємо чистий текстовий run
    run = p.add_run(new_text)
    run.font.name = 'Times New Roman'
    run.font.size = Pt(font_size_pt)
    if bold is not None:
        run.bold = bold

    # Додаємо commentRangeEnd та commentReference у кінець параграфа
    for ce in saved_comment_Ends:
        p_elem.append(ce)
    for cr in saved_comment_Refs:
        r_wrap = OxmlElement('w:r')
        r_wrap.append(cr)
        p_elem.append(r_wrap)


def insert_body_paragraph_after(ref_p, text: str, style_name: str = 'normal', bold: bool = False, first_line_mm: float = 12.5):
    """
    Вставляє новий відформатований за ДСТУ абзац одразу ПІСЛЯ параграфа ref_p,
    повертає створений об'єкт Paragraph.
    """
    new_p_elem = OxmlElement('w:p')
    ref_p._p.addnext(new_p_elem)
    new_p = docx.text.paragraph.Paragraph(new_p_elem, ref_p._parent)
    try:
        new_p.style = style_name
    except Exception:
        pass
    new_p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    new_p.paragraph_format.first_line_indent = Mm(first_line_mm)
    new_p.paragraph_format.line_spacing = 1.5
    new_p.paragraph_format.space_before = Pt(0)
    new_p.paragraph_format.space_after = Pt(0)

    run = new_p.add_run(text)
    run.font.name = 'Times New Roman'
    run.font.size = Pt(14)
    run.bold = bold
    return new_p


def insert_code_listing_after(ref_p, title_text: str, code_text: str):
    """Вставляє заголовок лістингу та блок коду за стандартом ДСТУ після параграфа ref_p."""
    p_title = insert_body_paragraph_after(ref_p, title_text, first_line_mm=12.5)
    p_title.paragraph_format.space_before = Pt(10)
    p_title.paragraph_format.space_after = Pt(4)

    new_p_elem = OxmlElement('w:p')
    p_title._p.addnext(new_p_elem)
    p_code = docx.text.paragraph.Paragraph(new_p_elem, ref_p._parent)
    p_code.alignment = WD_ALIGN_PARAGRAPH.LEFT
    p_code.paragraph_format.first_line_indent = Mm(0)
    p_code.paragraph_format.left_indent = Mm(12.5)
    p_code.paragraph_format.right_indent = Mm(10.0)
    p_code.paragraph_format.space_before = Pt(4)
    p_code.paragraph_format.space_after = Pt(8)
    p_code.paragraph_format.line_spacing = 1.0

    run = p_code.add_run(code_text.strip())
    run.font.name = 'Consolas'
    run.font.size = Pt(9.0)
    run.font.color.rgb = RGBColor(15, 23, 42)

    pPr = p_code._p.get_or_add_pPr()
    shd = parse_xml(f'<w:shd {nsdecls("w")} w:fill="F8FAFC"/>')
    pBdr = parse_xml(
        f'<w:pBdr {nsdecls("w")}>'
        f'<w:top w:val="single" w:sz="4" w:space="4" w:color="CBD5E1"/>'
        f'<w:left w:val="single" w:sz="12" w:space="6" w:color="0284C7"/>'
        f'<w:bottom w:val="single" w:sz="4" w:space="4" w:color="CBD5E1"/>'
        f'<w:right w:val="single" w:sz="4" w:space="4" w:color="CBD5E1"/>'
        f'</w:pBdr>'
    )
    pPr.append(shd)
    pPr.append(pBdr)
    return p_code


def remove_paragraph_safe(p):
    """Безпечно видаляє параграф, якщо в ньому немає коментарів або формул."""
    xml = p._p.xml
    if any(k in xml for k in ['commentRangeStart', 'commentRangeEnd', 'commentReference', 'oMath']):
        raise ValueError(f"Спроба видалити захищений параграф із коментарем або формулою: {p.text[:60]}")
    p._p.getparent().remove(p._p)


def find_para_by_prefix(doc, prefix: str, start_idx: int = 0):
    for i in range(start_idx, len(doc.paragraphs)):
        if doc.paragraphs[i].text.strip().startswith(prefix):
            return i, doc.paragraphs[i]
    raise ValueError(f"Параграф з префіксом '{prefix}' не знайдено!")


