"""
Автоматичний аудитор дотримання PRESENTATION_RULES.md для слайдів та плану виступу.
Перевіряє:
  1. Відсутність займенників першої особи множини (ми / наш* / нами / нам / нас);
  2. Відсутність категоричних заперечень та принизливої критики інших підходів;
  3. Відсутність ШІ-кліше та самозвеличення;
  4. Відсутність формалізму, мета-блоків та шаблонних вітань у слайдах;
  5. Відсутність застарілих несинхронізованих цифр (28%, 41%, 91%, 84.2%).
"""
import re
import sys
from pathlib import Path

BANNED_PATTERNS = [
    # 1. Займенники першої особи множини
    ("Займенник 1-ї особи множини", r"(?i)(?<![а-яіїєґ])(ми|наш[а-яіїєґ]*|нами|нам|нас)(?![а-яіїєґ])"),
    # 2. Категоричні заперечення та принизлива критика
    (
        "Категоричне заперечення / критика",
        r"(?i)\b(не відображає|не розрізняє|не містить|не дозволяє|не працюють|не працює|не здатен|не здатна|не здатні|унеможливлює|вичерпали свій ресурс|зайшли у глухий кут|безпорадн\w*|застаріл\w*|критичні вади|катастрофічний дефіцит|повна неспроможність|чорн\w* скриньк\w*)\b",
    ),
    # 3. ШІ-кліше та самозвеличення
    (
        "ШІ-кліше / самозвеличення",
        r"(?i)\b(варто зазначити|стрімкий розвиток|відіграє ключову роль|широкий спектр|слід підкреслити|не викликає сумніву|формує цілісний механізм|найкращий підхід|єдино правильне рішення|революційн\w*|проривн\w*|не має аналогів|посідає провідне місце)\b",
    ),
    # 4. Формалізм і мета-блоки
    (
        "Формалізм / мета-блок",
        r"(?i)(ключові елементи на слайді|для notebooklm|доброго дня,\s*шановні|мене звати|дякую за увагу|репліка доповідача|викладач каже)",
    ),
    # 5. Застарілі цифри, що суперечать тезам V-4.0
    (
        "Застарілі цифри (розсинхрон із тезами V-4.0)",
        r"(?i)(на 28%|на 41%|— 91%|84[.,]2%)",
    ),
]


def audit_file(path: Path) -> int:
    text = path.read_text(encoding="utf-8")
    violations = []
    for line_no, line in enumerate(text.splitlines(), start=1):
        for category, pattern in BANNED_PATTERNS:
            for m in re.finditer(pattern, line):
                violations.append((line_no, category, m.group(0), line.strip()))

    if violations:
        print(f"❌ AUDIT FAILED for {path} ({len(violations)} violations):")
        for line_no, category, match, snippet in violations:
            print(f"  L{line_no} [{category}] -> '{match}' | {snippet[:100]}")
        return 1

    print(f"✅ AUDIT PASSED: {path} (0 violations)")
    return 0


def main() -> int:
    base = Path(__file__).resolve().parent
    targets = [Path(arg) for arg in sys.argv[1:]] if len(sys.argv) > 1 else [
        base / "slides" / "SLIDES_SCRIPT.md",
    ]
    exit_code = 0
    for t in targets:
        exit_code |= audit_file(t)
    return exit_code


if __name__ == "__main__":
    sys.exit(main())
